# Ashtu si ne matematike, dhe ne python mund te kryejme veprime matematikore
# Per kete perdorim operatoret matematikor


# mbledhja(+), zbritja(-), shumezimi(*), pjestimi(/)

# Me poshte po ruajme ne nje variabel shumen e dy numrave
shuma1 = 5 + 6

# Ne mund te kryejme veprime matematikore dhe me vlerat e variablave
numri1 = 7
numri2 = 12

shuma2 = numri1 + numri2
# Po te printojme vleren e variablit "shuma2", do shohim se ai do te jete i barabarte me 19
print("Vlera e variablit shuma2:", shuma2)

# Le te provojme dhe veprimet e tjera
ndryshesa = numri2 - numri1
print("Ndryshesa", ndryshesa)

prodhimi = numri1 * numri2
print("Prodhimi:", prodhimi)

pjesetimi = numri2 / numri1
print("Pjesetimi:", pjesetimi)

mbetja = numri1 % numri2
print("Mbetja:", numri1 % numri2)
print("Mbetja:", mbetja)

fuqia = numri1 ** numri2
print("Fuqia:", numri1 ** numri2)
print("Fuqia:", fuqia)

heresi = numri2 // numri1
print("Fuqia:", heresi)

numri1 = 5
